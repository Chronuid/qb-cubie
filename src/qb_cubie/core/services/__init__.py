_SUBMODULES: frozenset[str] = frozenset({"doc_ensurance", "doc_frame", "docframe"})
_EXPORT_TO_SUBMODULE: dict[str, str] = {
    **{name: "doc_ensurance" for name in _DOC_ENSURANCE_EXPORTS},
    **{name: "doc_frame" for name in _DOC_FRAME_EXPORTS},
}

__all__ = sorted((*_DOC_ENSURANCE_EXPORTS, *_DOC_FRAME_EXPORTS, *_SUBMODULES))


def __getattr__(name: str) -> Any:
    """Lazily resolves service packages and re-exported symbols without loading sibling services."""
    if name in _SUBMODULES:
        return import_module(f".{name}", __name__)
    submodule = _EXPORT_TO_SUBMODULE.get(name)
    if submodule is not None:
        return getattr(import_module(f".{submodule}", __name__), name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
